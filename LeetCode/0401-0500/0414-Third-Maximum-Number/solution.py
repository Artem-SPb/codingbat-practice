from typing import List


class Solution:
    def thirdMax(self, nums: List[int]) -> int:
        """
        Находит третий по величине уникальный элемент массива за O(N).
        Использует логику выборочного обновления максимумов
        (пьедестал 3-х мест).
        """
        # Инициализируем 3 места минус бесконечностью
        m1 = m2 = m3 = float('-inf')

        for num in nums:
            # Игнорируем дубликаты, которые уже стоят на пьедестале
            if num in (m1, m2, m3):
                continue

            # Если число бьет абсолютный рекорд — сдвигаем всех вниз
            if num > m1:
                m3 = m2
                m2 = m1
                m1 = num
            # Если число бьет только второе место — сдвигаем третье
            elif num > m2:
                m3 = m2
                m2 = num
            # Если число подходит только на третье место
            elif num > m3:
                m3 = num

        # Если m3 так и осталось минус бесконечностью,
        # значит в массиве было меньше трех уникальных чисел.
        return m1 if m3 == float('-inf') else m3


# --- Блок самопроверки ---
if __name__ == "__main__":
    solution = Solution()

    # Тест 1: Классический случай
    assert solution.thirdMax([3, 2, 1]) == 1, "Ошибка в тесте 1"

    # Тест 2: Меньше 3 уникальных чисел
    assert solution.thirdMax([1, 2]) == 2, "Ошибка в тесте 2"

    # Тест 3: Наличие дубликатов
    assert solution.thirdMax([2, 2, 3, 1]) == 1, "Ошибка в тесте 3"

    # Тест 4: Работа с отрицательными числами
    assert solution.thirdMax([1, 2, -2147483648]) == (
        -2147483648, "Ошибка в тесте 4")

    # Тест 5: Большой массив с одинаковыми числами
    assert solution.thirdMax([1, 1, 1, 1, 1]) == 1, "Ошибка в тесте 5"

    print("Все тесты пройдены успешно!")
